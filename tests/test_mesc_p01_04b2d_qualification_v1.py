def request_kwargs(fixture_id: str, **overrides: Any) -> dict[str, Any]:
    """Return the exact request keyword arguments for one fixture.

    The three identity values are committed literal constants.  The facade
    regenerates and compares both digests itself, so supplying literals here is
    the fail-closed proof that the frozen identities are the real ones.
    """
    inputs = fx.fixture_inputs(fixture_id)
    proof, fixture_sha256, request_id = _IDENTITIES[fixture_id]
    kwargs: dict[str, Any] = {
        "fixture_schema_version": "1",
        "fixture_namespace": FIXTURE_NAMESPACE_PREFIX + fixture_id,
        "fixture_id": fixture_id,
        "fixture_sha256": fixture_sha256,
        "fixture_only": True,
        "non_evidence": True,
        "synthetic_identity_proof": proof,
        "request_id": request_id,
        "seed": fx.SEED,
        "policy_id": fx.POLICY_ID,
        "transformation_version": fx.TRANSFORMATION_VERSION,
        "ordered_rows": inputs.plan.ordered_rows,
        "source_labels": inputs.plan.source_labels,
        "partition_totals": dict(inputs.partition_totals),
        "leakage_findings": inputs.leakage_findings,
        "detection_methods": inputs.detection_methods,
        "execution_evidence_ref": inputs.execution_evidence_ref,
    }
    kwargs.update(overrides)
    return kwargs


def build_request(fixture_id: str, **overrides: Any) -> FixtureSplitRequest:
    """Return the exact ``FixtureSplitRequest`` for one qualification fixture."""
    return FixtureSplitRequest(**request_kwargs(fixture_id, **overrides))


