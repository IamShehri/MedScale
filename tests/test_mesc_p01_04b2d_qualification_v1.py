def acceptance_eligible(criteria: tuple[Criterion, ...]) -> bool:
    """Return whether every criterion is SATISFIED.

    A ``NOT APPLICABLE`` disposition records that B2D cannot qualify a criterion.
    It never converts to ``SATISFIED`` and never counts toward acceptance, and
    an ``UNSATISFIED`` or ``BLOCKED`` criterion can never be ignored.
    """
    return all(criterion.status == SATISFIED for criterion in criteria)


