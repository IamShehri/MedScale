def test_boundary_guard_itself_refuses_each_channel() -> None:
    """The guard must actually block, otherwise the boundary proves nothing."""
    with _side_effect_boundary():
        # Each channel is reached through an indirect reference so this probe
        # never contains a literal filesystem call of its own.
        opener = builtins.open
        connector = socket.socket
        runner = subprocess.run
        for attempt in (
            lambda: opener("x"),
            lambda: connector(),
            lambda: runner(["x"], check=False),
            time.time,
            random.random,
            lambda: os.urandom(1),
            lambda: os.environ["PATH"],
        ):
            try:
                attempt()
            except SideEffectAttemptError:
                continue
            raise AssertionError("a prohibited channel was not blocked")


def test_boundary_restores_every_channel_afterwards() -> None:
    before = (builtins.open, socket.socket, subprocess.run, time.time, os.urandom)
    with _side_effect_boundary():
        pass
    after = (builtins.open, socket.socket, subprocess.run, time.time, os.urandom)
    assert before == after
    assert isinstance(os.environ.get("PATH", ""), str)


