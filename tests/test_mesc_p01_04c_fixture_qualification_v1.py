# ---------------------------------------------------------------------------
# Side-effect boundary
# ---------------------------------------------------------------------------


class SideEffectAttemptError(AssertionError):
    """Raised when guarded code attempts a prohibited side-effect channel."""


class _ForbiddenEnviron(Mapping[str, str]):
    """An environment mapping that refuses every read."""

    def __getitem__(self, key: str) -> str:
        raise SideEffectAttemptError("environment read attempted")

    def __iter__(self) -> Iterator[str]:
        raise SideEffectAttemptError("environment iteration attempted")

    def __len__(self) -> int:
        raise SideEffectAttemptError("environment length read attempted")


def _forbid(channel: str) -> object:
    def _refuse(*args: object, **kwargs: object) -> object:
        raise SideEffectAttemptError(f"{channel} attempted")

    return _refuse


@contextlib.contextmanager
def _side_effect_boundary() -> Iterator[None]:
    """Disable filesystem, socket, subprocess, clock, environment and randomness.

    Restoration happens in ``finally`` before any assertion runs, so a failing
    expectation is reported normally instead of tripping the guard itself.
    """
    targets: tuple[tuple[object, str, object], ...] = (
        (builtins, "open", _forbid("filesystem open")),
        (io, "open", _forbid("filesystem open")),
        (pathlib.Path, "open", _forbid("path open")),
        (pathlib.Path, "write_text", _forbid("path write")),
        (pathlib.Path, "write_bytes", _forbid("path write")),
        (os, "remove", _forbid("filesystem unlink")),
        (os, "urandom", _forbid("urandom")),
        (os, "getenv", _forbid("environment read")),
        (os, "environ", _ForbiddenEnviron()),
        (socket, "socket", _forbid("socket creation")),
        (socket, "create_connection", _forbid("socket connection")),
        (subprocess, "Popen", _forbid("subprocess execution")),
        (subprocess, "run", _forbid("subprocess execution")),
        (time, "time", _forbid("clock access")),
        (time, "time_ns", _forbid("clock access")),
        (time, "monotonic", _forbid("clock access")),
        (random, "random", _forbid("randomness")),
        (random, "randint", _forbid("randomness")),
        (random, "choice", _forbid("randomness")),
    )
    saved = [(holder, name, getattr(holder, name)) for holder, name, _ in targets]
    try:
        for holder, name, replacement in targets:
            setattr(holder, name, replacement)
        yield
    finally:
        for holder, name, original in saved:
            setattr(holder, name, original)


def _run_guarded(request: FixtureSplitRequest) -> FixtureSplitResult:
    with _side_effect_boundary():
        return FixtureSplitFacade.run(request)


