@pytest.mark.parametrize(
    ("builder", "expected_request_id", "expected_hash", "expected_fingerprint"),
    [
        (_small_20_request, SMALL_20_REQUEST_ID, SMALL_20_SPLIT_HASH, SMALL_20_SPLIT_FINGERPRINT),
        (
            _single_example_request,
            SINGLE_REQUEST_ID,
            SINGLE_SPLIT_HASH,
            SINGLE_SPLIT_FINGERPRINT,
        ),
        (
            _all_one_label_request,
            ALL_ONE_REQUEST_ID,
            ALL_ONE_SPLIT_HASH,
            ALL_ONE_SPLIT_FINGERPRINT,
        ),
    ],
)
def test_three_fresh_runs_are_byte_identical(
    builder: object,
    expected_request_id: str,
    expected_hash: str,
    expected_fingerprint: str,
) -> None:
    """Three fresh, semantically identical requests must agree on every surface."""
    assert callable(builder)
    requests = [builder() for _ in range(3)]
    assert len({id(item) for item in requests}) == 3
    results = [_run_guarded(item) for item in requests]

    first = results[0]
    for other in results[1:]:
        assert other.request_id == first.request_id
        assert other.split_manifest.computed_split_hash == first.split_manifest.computed_split_hash
        assert (
            other.split_fingerprint_record.split_fingerprint
            == first.split_fingerprint_record.split_fingerprint
        )
        assert other.split_manifest.split_assignments == first.split_manifest.split_assignments
        for name in BYTE_SURFACE_NAMES:
            assert getattr(other, name) == getattr(first, name)
        observed = tuple(
            (item.role, item.sha256, item.byte_size)
            for item in other.split_fingerprint_record.identity.artifact_descriptors
        )
        baseline = tuple(
            (item.role, item.sha256, item.byte_size)
            for item in first.split_fingerprint_record.identity.artifact_descriptors
        )
        assert observed == baseline

    for item in requests:
        assert item.fixture_sha256 == requests[0].fixture_sha256
    assert first.request_id == expected_request_id
    assert first.split_manifest.computed_split_hash == expected_hash
    assert first.split_fingerprint_record.split_fingerprint == expected_fingerprint


