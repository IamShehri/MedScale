def _source_record_hash(ordinal: int) -> str:
    """Return a synthetic 64-hex record hash derived only from the row ordinal."""
    return hashlib.sha256(f"mesc-p01-04c-source-record:{ordinal:02d}".encode()).hexdigest()


def _synthetic_proof(fixture_id: str) -> str:
    """Return the declared synthetic-batch marker for a fixture identifier."""
    digest = hashlib.sha256(f"mesc-p01-04c-synthetic-batch:{fixture_id}".encode()).hexdigest()
    return SYNTHETIC_PROOF_PREFIX + digest


def _ordered_rows(count: int) -> tuple[OrderedExampleRow, ...]:
    return tuple(
        OrderedExampleRow(
            original_example_id=f"p01-04c-example-{ordinal:02d}",
            row_ordinal=ordinal,
            source_document_id=f"p01-04c-document-{ordinal:02d}",
        )
        for ordinal in range(count)
    )


def _source_labels(decisions: tuple[Decision, ...]) -> tuple[SourceLabelRow, ...]:
    return tuple(
        SourceLabelRow(
            dataset_id=DATASET_ID,
            dataset_revision=DATASET_REVISION,
            configuration=CONFIGURATION,
            original_example_id=f"p01-04c-example-{ordinal:02d}",
            source_document_id=f"p01-04c-document-{ordinal:02d}",
            decision=decision,
            source_record_hash=_source_record_hash(ordinal),
        )
        for ordinal, decision in enumerate(decisions)
    )


def _build_request(
    *,
    fixture_id: str,
    decisions: tuple[Decision, ...],
    partition_totals: Mapping[str, int],
    fixture_sha256: str,
    request_id: str,
) -> FixtureSplitRequest:
    """Return a fresh synthetic request built only from literal inputs.

    ``fixture_sha256`` and ``request_id`` are supplied as frozen literals rather
    than recomputed here, so the facade's identity verification is a real check
    against a transcribed constant instead of a tautology.
    """
    return FixtureSplitRequest(
        fixture_schema_version="1",
        fixture_namespace=FIXTURE_NAMESPACE_PREFIX + fixture_id,
        fixture_id=fixture_id,
        fixture_sha256=fixture_sha256,
        fixture_only=True,
        non_evidence=True,
        synthetic_identity_proof=_synthetic_proof(fixture_id),
        request_id=request_id,
        seed=SPLIT_SEED,
        policy_id=POLICY_ID,
        transformation_version=TRANSFORMATION_VERSION,
        ordered_rows=_ordered_rows(len(decisions)),
        source_labels=_source_labels(decisions),
        partition_totals=dict(partition_totals),
        leakage_findings=(),
        detection_methods=DETECTION_METHODS,
        execution_evidence_ref=EXECUTION_EVIDENCE_REF,
    )


