def _assert_surfaces(result: FixtureSplitResult, expected: Mapping[str, tuple[str, int]]) -> None:
    for name in BYTE_SURFACE_NAMES:
        payload = getattr(result, name)
        assert type(payload) is bytes
        expected_digest, expected_size = expected[name]
        assert hashlib.sha256(payload).hexdigest() == expected_digest
        assert len(payload) == expected_size
        assert payload.endswith(b"\n")
        assert not payload.endswith(b"\n\n")


def _assert_no_real_membership(result: FixtureSplitResult) -> None:
    """Every assigned identity must trace back to a synthetic P01-04C row."""
    for assignment in result.split_manifest.split_assignments:
        assert assignment.source_document_id.startswith("p01-04c-document-")
        assert assignment.split in {"train", "validation", "test"}


